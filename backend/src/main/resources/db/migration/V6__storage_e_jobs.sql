-- Storage por chave (local ou S3), SHA-256 contra duplicados e fila de processamento em segundo plano.

-- No storage local a raiz continua sendo o diretorio de uploads, entao a chave dos arquivos antigos e o nome interno.
ALTER TABLE documento_fiscal RENAME COLUMN caminho_arquivo TO chave_armazenamento;
UPDATE documento_fiscal SET chave_armazenamento = nome_arquivo_interno;

-- Arquivos antigos ficam sem hash (NULL nao conflita com o UNIQUE).
ALTER TABLE documento_fiscal ADD COLUMN sha256 VARCHAR(64);
ALTER TABLE documento_fiscal ADD CONSTRAINT uk_documento_cliente_sha256 UNIQUE (cliente_id, sha256);

CREATE TABLE job_processamento (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo         VARCHAR(40)  NOT NULL,
    documento_id BIGINT       NOT NULL REFERENCES documento_fiscal (id) ON DELETE CASCADE,
    status       VARCHAR(20)  NOT NULL,
    tentativas   INTEGER      NOT NULL DEFAULT 0,
    mensagem     VARCHAR(1000),
    inicio       TIMESTAMP(6),
    fim          TIMESTAMP(6),
    data_criacao TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_job_status ON job_processamento (status);
CREATE INDEX ix_job_documento ON job_processamento (documento_id);
