-- Plano de Contas Referencial da RFB (tabelas dinâmicas oficiais), versionado por ano e tipo de plano.
-- Carregado pela ImportacaoPlanoReferencial a partir de src/main/resources/plano-referencial (fonte em tabelas.txt).

CREATE TABLE tabela_referencial (
    tabela       VARCHAR(60)  PRIMARY KEY, -- nome oficial, ex.: SPEDECF_DINAMICA_L100_A_2021
    ano          INTEGER      NOT NULL,
    plano        VARCHAR(4)   NOT NULL,    -- 0000.COD_PLAN_REF
    demonstracao VARCHAR(3)   NOT NULL,    -- BP | DRE
    versao       INTEGER,                  -- "versão=N" do cabeçalho do arquivo
    sha256       VARCHAR(64)  NOT NULL,
    fonte        VARCHAR(500) NOT NULL,
    importada_em TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE conta_referencial (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tabela          VARCHAR(60)  NOT NULL REFERENCES tabela_referencial (tabela) ON DELETE CASCADE,
    codigo          VARCHAR(60)  NOT NULL,
    descricao       VARCHAR(500) NOT NULL,
    data_inicio     DATE,
    data_fim        DATE,
    ordem           INTEGER      NOT NULL,
    sintetica       BOOLEAN      NOT NULL,
    codigo_superior VARCHAR(60),
    nivel           INTEGER      NOT NULL,
    natureza        VARCHAR(2),
    CONSTRAINT uk_conta_referencial UNIQUE (tabela, codigo)
);
