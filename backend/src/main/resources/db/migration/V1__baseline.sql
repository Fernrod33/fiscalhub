-- Baseline do schema (gerado pelo Hibernate 6 em PostgreSQL 18 via pg_dump --schema-only --no-owner --no-privileges,
-- revisado a mao). Enums sao VARCHAR sem CHECK, para que novos valores nao exijam migracao.
-- Tabelas de documento fiscal ficam na V2.

CREATE TABLE usuario (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(100) NOT NULL,
    email            VARCHAR(100) NOT NULL,
    senha            VARCHAR(120) NOT NULL,
    cpf              VARCHAR(14),
    telefone         VARCHAR(20),
    ativo            BOOLEAN      NOT NULL,
    data_criacao     TIMESTAMP(6) NOT NULL,
    data_atualizacao TIMESTAMP(6),
    CONSTRAINT usuario_email_key UNIQUE (email)
);

CREATE TABLE empresa (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id          BIGINT       NOT NULL REFERENCES usuario (id),
    razao_social        VARCHAR(150) NOT NULL,
    nome_fantasia       VARCHAR(150),
    cnpj                VARCHAR(18)  NOT NULL,
    inscricao_estadual  VARCHAR(20),
    inscricao_municipal VARCHAR(20),
    endereco            VARCHAR(200),
    cidade              VARCHAR(100),
    estado              VARCHAR(2),
    cep                 VARCHAR(10),
    telefone            VARCHAR(20),
    ativa               BOOLEAN      NOT NULL,
    data_criacao        TIMESTAMP(6) NOT NULL,
    data_atualizacao    TIMESTAMP(6),
    CONSTRAINT empresa_cnpj_key UNIQUE (cnpj)
);

CREATE TABLE declaracao (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id       BIGINT        NOT NULL REFERENCES usuario (id),
    empresa_id       BIGINT        NOT NULL REFERENCES empresa (id),
    tipo             VARCHAR(50)   NOT NULL,
    tributo          VARCHAR(20),
    periodo_inicio   DATE          NOT NULL,
    periodo_fim      DATE          NOT NULL,
    valor_total      NUMERIC(15,2) NOT NULL,
    valor_imposto    NUMERIC(15,2),
    status           VARCHAR(20)   NOT NULL,
    data_vencimento  DATE,
    data_pagamento   DATE,
    observacoes      VARCHAR(500),
    data_criacao     TIMESTAMP(6)  NOT NULL,
    data_atualizacao TIMESTAMP(6)
);

CREATE TABLE simulacao_parcelamento (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    declaracao_id            BIGINT        NOT NULL REFERENCES declaracao (id),
    orgao                    VARCHAR(30)   NOT NULL,
    modalidade               VARCHAR(30)   NOT NULL,
    valor_original           NUMERIC(15,2) NOT NULL,
    data_vencimento_original DATE          NOT NULL,
    data_calculo             DATE          NOT NULL,
    dias_em_atraso           INTEGER,
    percentual_multa_mora    NUMERIC(8,4),
    valor_multa_mora         NUMERIC(15,2),
    percentual_multa_oficio  NUMERIC(8,4),
    valor_multa_oficio       NUMERIC(15,2),
    percentual_juros_mora    NUMERIC(8,4),
    valor_juros              NUMERIC(15,2),
    indice_utilizado         VARCHAR(10),
    valor_atualizado         NUMERIC(15,2),
    valor_entrada            NUMERIC(15,2),
    numero_parcelas          INTEGER,
    valor_parcela            NUMERIC(15,2),
    custo_total              NUMERIC(15,2),
    economia_obtida          NUMERIC(15,2),
    taxa_juros               NUMERIC(5,2),
    valor_total              NUMERIC(15,2),
    aprovada                 BOOLEAN       NOT NULL,
    observacoes              VARCHAR(500),
    memoria_calculo_json     TEXT,
    data_criacao             TIMESTAMP(6)  NOT NULL,
    data_atualizacao         TIMESTAMP(6)
);

CREATE TABLE parcela_simulacao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    simulacao_id    BIGINT        NOT NULL REFERENCES simulacao_parcelamento (id),
    numero_parcela  INTEGER       NOT NULL,
    data_vencimento DATE          NOT NULL,
    valor_parcela   NUMERIC(15,2) NOT NULL,
    saldo_restante  NUMERIC(15,2) NOT NULL
);

CREATE TABLE indice_monetario (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo  VARCHAR(10)   NOT NULL,
    ano   INTEGER       NOT NULL,
    mes   INTEGER       NOT NULL,
    valor NUMERIC(12,6) NOT NULL,
    CONSTRAINT indice_monetario_tipo_ano_mes_key UNIQUE (tipo, ano, mes)
);
