-- Fase 2a: o que a empresa apurou, lido das escriturações fiscais (ECF, EFD-Contribuições, EFD ICMS/IPI). Um modelo só
-- para todos os tributos e fontes; tudo pendurado na escrituração de origem (reprocessar ou excluir o documento apaga
-- o que ele gerou). Valores positivos como no arquivo; cada valor aponta para o registro e a linha de onde veio.

-- escrituracao_contabil passa a guardar toda escrituração importada (contábil ou fiscal). CNPJ do estabelecimento: a
-- EFD ICMS/IPI é por estabelecimento, e a retificação substitui a do mesmo CNPJ e período.
ALTER TABLE escrituracao_contabil ADD COLUMN cnpj VARCHAR(14);
UPDATE escrituracao_contabil e SET cnpj = c.cnpj FROM cliente c WHERE c.id = e.cliente_id;

CREATE TABLE apuracao_tributo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id  BIGINT         NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    cliente_id       BIGINT         NOT NULL REFERENCES cliente (id),
    documento_id     BIGINT         NOT NULL REFERENCES documento_fiscal (id) ON DELETE CASCADE,
    tributo          VARCHAR(20)    NOT NULL, -- TipoTributo: IRPJ, CSLL, PIS, COFINS, ICMS, ICMS_ST, ICMS_DIFAL, ICMS_FCP, IPI
    esfera           VARCHAR(10)    NOT NULL, -- FEDERAL | ESTADUAL
    uf               VARCHAR(2),              -- tributo estadual: UF da apuração (ICMS-ST e DIFAL são por UF)
    data_inicio      DATE           NOT NULL,
    data_fim         DATE           NOT NULL,
    periodicidade    VARCHAR(12)    NOT NULL, -- MENSAL | TRIMESTRAL | ANUAL
    regime           VARCHAR(20),             -- LUCRO_REAL | LUCRO_PRESUMIDO | LUCRO_ARBITRADO | NAO_CUMULATIVO | CUMULATIVO
    descricao        VARCHAR(200)   NOT NULL, -- ex.: "Estimativa mensal", "Ajuste anual", "Operações próprias"
    base_calculo     NUMERIC(19, 2),
    valor_apurado    NUMERIC(19, 2),
    deducoes         NUMERIC(19, 2),          -- deduções e créditos utilizados
    valor_a_recolher NUMERIC(19, 2) NOT NULL,
    saldo_credor     NUMERIC(19, 2),          -- saldo credor a transportar para o período seguinte
    origem           JSONB          NOT NULL  -- campo -> {"registro": "E110", "linha": 1234}
);
CREATE INDEX ix_apuracao_cliente ON apuracao_tributo (cliente_id, tributo, data_fim);
CREATE INDEX ix_apuracao_escrituracao ON apuracao_tributo (escrituracao_id);

-- Linhas que compõem o cálculo (e-Lalur/e-Lacs, demonstração do lucro presumido, ajustes do ICMS, créditos do PIS)
CREATE TABLE detalhe_apuracao (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apuracao_id  BIGINT         NOT NULL REFERENCES apuracao_tributo (id) ON DELETE CASCADE,
    ordem        INTEGER        NOT NULL,
    grupo        VARCHAR(40),             -- ex.: ADICAO, EXCLUSAO, COMPENSACAO, LUCRO, CALCULO, AJUSTE, CREDITO
    codigo       VARCHAR(60),             -- código da tabela dinâmica (ECF) ou de ajuste (E111, M100.COD_CRED)
    descricao    VARCHAR(500)   NOT NULL,
    valor        NUMERIC(19, 2) NOT NULL,
    registro     VARCHAR(10)    NOT NULL,
    linha        BIGINT         NOT NULL
);
CREATE INDEX ix_detalhe_apuracao ON detalhe_apuracao (apuracao_id, ordem);

-- Obrigações a recolher declaradas na apuração (E116, E250, E316): preparadas para a conciliação com o pago (Fase 2b)
CREATE TABLE obrigacao_recolher (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    apuracao_id     BIGINT         NOT NULL REFERENCES apuracao_tributo (id) ON DELETE CASCADE,
    codigo_obrigacao VARCHAR(3),             -- COD_OR (tabela 5.4 do guia)
    codigo_receita  VARCHAR(30),             -- COD_REC (código de receita da UF)
    vencimento      DATE,
    valor           NUMERIC(19, 2) NOT NULL,
    registro        VARCHAR(10)    NOT NULL,
    linha           BIGINT         NOT NULL
);
CREATE INDEX ix_obrigacao_apuracao ON obrigacao_recolher (apuracao_id);

-- Saldos que passam de um período para outro: prejuízo fiscal e base negativa (Parte B do e-Lalur/e-Lacs), créditos de
-- PIS e COFINS (1100/1500) e saldos credores de ICMS, ICMS-ST e IPI
CREATE TABLE saldo_fiscal (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id BIGINT         NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    cliente_id      BIGINT         NOT NULL REFERENCES cliente (id),
    tipo            VARCHAR(30)    NOT NULL, -- PREJUIZO_FISCAL | BASE_NEGATIVA_CSLL | CREDITO_PIS | CREDITO_COFINS | SALDO_CREDOR_ICMS ...
    uf              VARCHAR(2),
    codigo          VARCHAR(60),             -- conta da Parte B, código do crédito ou período de origem
    descricao       VARCHAR(500)   NOT NULL,
    data_inicio     DATE           NOT NULL,
    data_fim        DATE           NOT NULL,
    saldo_inicial   NUMERIC(19, 2),
    saldo_final     NUMERIC(19, 2) NOT NULL,
    registro        VARCHAR(10)    NOT NULL,
    linha           BIGINT         NOT NULL
);
CREATE INDEX ix_saldo_fiscal_cliente ON saldo_fiscal (cliente_id, tipo, data_fim);
CREATE INDEX ix_saldo_fiscal_escrituracao ON saldo_fiscal (escrituracao_id);
