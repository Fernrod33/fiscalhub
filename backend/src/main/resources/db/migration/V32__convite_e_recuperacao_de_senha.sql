-- Tokens de uso único enviados por e-mail: convite (72 h) e recuperação de senha (30 min). Só o SHA-256 fica no banco;
-- o valor vai apenas no link do e-mail. usado_em também marca o token substituído por um mais novo do mesmo tipo.
CREATE TABLE token_acesso (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT       NOT NULL REFERENCES usuario (id),
    tipo       VARCHAR(20)  NOT NULL,
    hash       CHAR(64)     NOT NULL UNIQUE,
    criado_em  TIMESTAMP(6) NOT NULL DEFAULT now(),
    expira_em  TIMESTAMP(6) NOT NULL,
    usado_em   TIMESTAMP(6)
);
CREATE INDEX ix_token_acesso_usuario ON token_acesso (usuario_id, tipo);

