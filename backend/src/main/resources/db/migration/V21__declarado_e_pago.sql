-- Fase 2b: o que foi declarado (DCTF Mensal em PDF ou .dec, DCTFWeb, conta corrente do ICMS) e o que foi pago (DARF,
-- relatório consolidado de pagamentos, GR-PR e relação de GR-PR). Também pendurados na escrituração do documento: a
-- retificadora de uma declaração substitui a original do mesmo período (escrituração SUBSTITUIDA, histórico mantido).

CREATE TABLE debito_declarado (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id  BIGINT         NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    cliente_id       BIGINT         NOT NULL REFERENCES cliente (id),
    codigo_receita   VARCHAR(10)    NOT NULL, -- como na declaração ("5123-01")
    tributo          VARCHAR(20),             -- pela tabela de códigos de receita; null se o código não está nela
    periodo          DATE           NOT NULL, -- primeiro dia do mês do período de apuração
    vencimento       DATE,
    valor            NUMERIC(15, 2) NOT NULL,
    valor_pago       NUMERIC(15, 2),          -- vinculações informadas na declaração
    valor_compensado NUMERIC(15, 2),
    valor_suspenso   NUMERIC(15, 2),
    valor_parcelado  NUMERIC(15, 2),
    pagina           INTEGER,                 -- null no .dec (o trecho traz o registro)
    linha            INTEGER        NOT NULL,
    trecho           VARCHAR(1000)  NOT NULL
);
CREATE INDEX ix_declarado_cliente ON debito_declarado (cliente_id, periodo);
CREATE INDEX ix_declarado_escrituracao ON debito_declarado (escrituracao_id);

CREATE TABLE pagamento (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id  BIGINT         NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    cliente_id       BIGINT         NOT NULL REFERENCES cliente (id),
    documento        VARCHAR(10)    NOT NULL, -- DARF | DAS | GR_PR
    numero           VARCHAR(60),             -- número do documento de arrecadação (a GR-PR individual não traz)
    chave            VARCHAR(120)   NOT NULL, -- o mesmo pagamento visto em dois documentos tem a mesma chave
    codigo_receita   VARCHAR(10),
    tributo          VARCHAR(20),
    periodo          DATE,
    referencia       VARCHAR(30),             -- como no documento ("08/2026", "12/36")
    vencimento       DATE,
    data_pagamento   DATE           NOT NULL,
    principal        NUMERIC(15, 2),
    multa            NUMERIC(15, 2),
    juros            NUMERIC(15, 2),
    total            NUMERIC(15, 2) NOT NULL,
    parcelamento     VARCHAR(60),             -- parcela de parcelamento ou transação: o número dele
    pagina           INTEGER,
    linha            INTEGER        NOT NULL,
    trecho           VARCHAR(1000)  NOT NULL
);
CREATE INDEX ix_pagamento_cliente ON pagamento (cliente_id, chave);
CREATE INDEX ix_pagamento_escrituracao ON pagamento (escrituracao_id);
