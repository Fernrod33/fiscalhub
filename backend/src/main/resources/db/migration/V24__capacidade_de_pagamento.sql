-- Fase 4: capacidade de pagamento (CAPAG federal, classificação do PR, análise gerencial).

-- Dados de cada dívida ativa lidos dos documentos (extrato do Regularize, conta corrente/dívida ativa do PR, RTI): o que
-- as metodologias usam e o débito não guarda. Junta-se ao débito pelo número (inscrição ou CDA).
CREATE TABLE divida_detalhe (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id  BIGINT        NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    cliente_id       BIGINT        NOT NULL REFERENCES cliente (id),
    orgao            VARCHAR(20)   NOT NULL, -- OrgaoCredor
    numero           VARCHAR(60)   NOT NULL, -- inscrição ou CDA, como no documento
    data_inscricao   DATE,
    origem_divida    VARCHAR(40),            -- PR: Imposto declarado | Lançamento de ofício
    ajuizamento      VARCHAR(40),            -- PR: Não ajuizada | Ajuizada | Desistência
    parcelamentos    INTEGER,                -- PR: parcelamentos da dívida (com o atual)
    garantia         VARCHAR(200),           -- PGFN
    suspensao_desde  DATE,                   -- PGFN: exigibilidade suspensa por decisão judicial desde
    classe_oficial   VARCHAR(5),             -- PR: classe da CDA no RTI
    data_referencia  DATE          NOT NULL,
    pagina           INTEGER,
    linha            INTEGER       NOT NULL,
    trecho           VARCHAR(1000) NOT NULL
);
CREATE INDEX ix_divida_detalhe_cliente ON divida_detalhe (cliente_id, numero);
CREATE INDEX ix_divida_detalhe_escrituracao ON divida_detalhe (escrituracao_id);

-- Situação cadastral do contribuinte num órgão (CAD/ICMS no PR, CNPJ na RFB), como no documento.
CREATE TABLE situacao_cadastral (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id  BIGINT        NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    cliente_id       BIGINT        NOT NULL REFERENCES cliente (id),
    orgao            VARCHAR(20)   NOT NULL, -- SEFA_PR | RFB
    situacao         VARCHAR(80)   NOT NULL,
    desde            DATE,
    data_referencia  DATE          NOT NULL,
    pagina           INTEGER,
    linha            INTEGER       NOT NULL,
    trecho           VARCHAR(1000) NOT NULL
);
CREATE INDEX ix_situacao_cadastral_cliente ON situacao_cadastral (cliente_id, orgao);
CREATE INDEX ix_situacao_cadastral_escrituracao ON situacao_cadastral (escrituracao_id);

-- Regras das metodologias como dado: faixas, índices e prazos do texto oficial, com vigência e fonte (URL e SHA-256 do
-- texto baixado). Norma nova = linha nova com a vigência; a antiga fica (relatórios emitidos citam a versão).
CREATE TABLE regra_capacidade_pagamento (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    orgao           VARCHAR(20)   NOT NULL, -- PGFN | SEFA_PR
    chave           VARCHAR(60)   NOT NULL, -- ex.: PR_DEVEDOR_CLASSES
    norma           VARCHAR(200)  NOT NULL,
    artigo          VARCHAR(100)  NOT NULL,
    vigencia_inicio DATE          NOT NULL,
    vigencia_fim    DATE,
    parametros      JSONB         NOT NULL,
    fonte_url       VARCHAR(500)  NOT NULL,
    fonte_sha256    VARCHAR(64),
    fonte_data      DATE          NOT NULL,
    observacao      VARCHAR(1000),
    CONSTRAINT uk_regra_capacidade UNIQUE (chave, vigencia_inicio)
);

-- Parâmetros das estimativas e da análise gerencial, editáveis por escritório (sem linha = padrão do código).
CREATE TABLE parametro_capacidade (
    escritorio_id   BIGINT       PRIMARY KEY REFERENCES escritorio (id),
    parametros      JSONB        NOT NULL,
    atualizado_em   TIMESTAMP(6) NOT NULL,
    atualizado_por  BIGINT       NOT NULL REFERENCES usuario (id)
);

-- De-para do plano referencial para a categoria da DFC direta: o padrão é o arquivo versionado
-- (resources/capacidade/dfc-depara.txt); cada escritório pode sobrepor prefixos.
CREATE TABLE dfc_depara_escritorio (
    escritorio_id   BIGINT       NOT NULL REFERENCES escritorio (id),
    prefixo         VARCHAR(60)  NOT NULL,
    categoria       VARCHAR(40)  NOT NULL,
    PRIMARY KEY (escritorio_id, prefixo)
);

