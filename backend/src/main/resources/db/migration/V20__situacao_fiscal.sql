-- Fase 2b: débitos, parcelamentos, pendências e capacidade de pagamento oficial, lidos dos documentos dos órgãos
-- (Relatório de Situação Fiscal, Regularize, CAPAG, conta corrente e RTI do PR). Cada documento lido vira uma
-- escrituracao_contabil (origem = tipo do documento, versao_leiaute = versão do layout do adaptador) e tudo o que ele
-- gerou pende dela (reprocessar ou excluir apaga). A mesma dívida vista em dois documentos fica uma linha por documento,
-- com a mesma chave; a consulta junta as fontes (vale a mais recente). Origem de PDF: página, linha e trecho.

-- origem = tipo do documento (RELATORIO_SITUACAO_FISCAL...); versão do layout do adaptador (ficticio-2026-10)
ALTER TABLE escrituracao_contabil
    ALTER COLUMN origem TYPE VARCHAR(40),
    ALTER COLUMN versao_leiaute TYPE VARCHAR(30);

ALTER TABLE debito
    ADD COLUMN escrituracao_id    BIGINT REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    ADD COLUMN chave              VARCHAR(120),  -- INSCRICAO|<número> ou <órgão>|<tributo>|<competência>
    ADD COLUMN data_referencia    DATE,          -- data do documento de origem (a mais recente vale)
    ADD COLUMN codigo_receita     VARCHAR(10),
    ADD COLUMN periodo            VARCHAR(60),   -- período como escrito no documento ("2019", "03/2022 a 06/2022")
    ADD COLUMN valor_encargo      NUMERIC(15, 2),
    ADD COLUMN valor_total        NUMERIC(15, 2), -- total como no documento (saldo consolidado, valor atualizado)
    ADD COLUMN situacao_documento VARCHAR(200),  -- situação como escrita no documento
    ADD COLUMN numero_processo    VARCHAR(60),
    ADD COLUMN ajuizado           BOOLEAN,
    ADD COLUMN negociacao         VARCHAR(300),
    ADD COLUMN pagina             INTEGER,
    ADD COLUMN linha              INTEGER,
    ADD COLUMN trecho             VARCHAR(1000),
    ALTER COLUMN data_vencimento DROP NOT NULL, -- inscrição em dívida ativa: o extrato não traz vencimento
    ALTER COLUMN valor_principal DROP NOT NULL; -- inscrição listada no relatório de situação fiscal sem valores
CREATE INDEX ix_debito_chave ON debito (cliente_id, chave);
CREATE INDEX ix_debito_escrituracao ON debito (escrituracao_id);

CREATE TABLE parcelamento (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id    BIGINT         NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    cliente_id         BIGINT         NOT NULL REFERENCES cliente (id),
    orgao              VARCHAR(20)    NOT NULL, -- OrgaoCredor
    numero             VARCHAR(60)    NOT NULL,
    modalidade         VARCHAR(200),            -- como no documento (transação por adesão, parcelamento estadual...)
    parcelas_pagas     INTEGER,
    parcelas_total     INTEGER,
    valor_parcela      NUMERIC(15, 2),
    saldo              NUMERIC(15, 2),
    situacao           VARCHAR(20)    NOT NULL, -- EM_DIA | EM_ATRASO | RESCINDIDO
    situacao_documento VARCHAR(200),
    debitos            VARCHAR(1000),           -- inscrições/CDAs vinculadas, separadas por "; "
    data_referencia    DATE           NOT NULL,
    pagina             INTEGER,
    linha              INTEGER        NOT NULL,
    trecho             VARCHAR(1000)  NOT NULL
);
CREATE INDEX ix_parcelamento_cliente ON parcelamento (cliente_id, orgao, numero);
CREATE INDEX ix_parcelamento_escrituracao ON parcelamento (escrituracao_id);

CREATE TABLE pendencia_fiscal (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id  BIGINT         NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    cliente_id       BIGINT         NOT NULL REFERENCES cliente (id),
    tipo             VARCHAR(40)    NOT NULL, -- OMISSAO_DECLARACAO | PROCESSO_SUSPENSO | ...
    descricao        VARCHAR(500)   NOT NULL,
    periodo          DATE,                    -- primeiro dia do mês, quando houver
    situacao         VARCHAR(200),
    data_referencia  DATE           NOT NULL,
    pagina           INTEGER,
    linha            INTEGER        NOT NULL,
    trecho           VARCHAR(1000)  NOT NULL
);
CREATE INDEX ix_pendencia_cliente ON pendencia_fiscal (cliente_id);
CREATE INDEX ix_pendencia_escrituracao ON pendencia_fiscal (escrituracao_id);

-- Insumo da Fase 4 (capacidade de pagamento): o que o órgão calculou, como no documento
CREATE TABLE capacidade_pagamento_oficial (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id    BIGINT         NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    cliente_id         BIGINT         NOT NULL REFERENCES cliente (id),
    fonte              VARCHAR(20)    NOT NULL, -- PGFN (Regularize/CAPAG) | SEFA_PR (RTI)
    classe             VARCHAR(5),
    capacidade         NUMERIC(17, 2),
    passivo            NUMERIC(17, 2),
    data_referencia    DATE           NOT NULL,
    classe_consistente BOOLEAN,                 -- classe x capacidade/passivo pela Portaria PGFN 6.757/2022
    pagina             INTEGER,
    linha              INTEGER        NOT NULL,
    trecho             VARCHAR(1000)  NOT NULL
);
CREATE INDEX ix_capacidade_cliente ON capacidade_pagamento_oficial (cliente_id);
CREATE INDEX ix_capacidade_escrituracao ON capacidade_pagamento_oficial (escrituracao_id);
