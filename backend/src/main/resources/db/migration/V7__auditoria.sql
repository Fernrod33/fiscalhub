-- Trilha de auditoria: so insercao. O trigger impede UPDATE e DELETE inclusive fora da aplicacao.

CREATE TABLE auditoria_evento (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escritorio_id BIGINT REFERENCES escritorio (id),
    usuario_id    BIGINT REFERENCES usuario (id),
    acao          VARCHAR(60)  NOT NULL,
    recurso_tipo  VARCHAR(40),
    recurso_id    BIGINT,
    data_hora     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ip            VARCHAR(45),
    detalhes      JSONB
);
CREATE INDEX ix_auditoria_escritorio_data ON auditoria_evento (escritorio_id, data_hora DESC);

CREATE FUNCTION auditoria_somente_insercao() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'auditoria_evento aceita somente insercao';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_auditoria_somente_insercao
    BEFORE UPDATE OR DELETE ON auditoria_evento
    FOR EACH ROW EXECUTE FUNCTION auditoria_somente_insercao();
