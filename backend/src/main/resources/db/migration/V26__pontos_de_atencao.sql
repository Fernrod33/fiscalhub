-- Fase 6: pontos de atenção. Cada achado de uma regra (resources/pontos/regras.json + classe RegraPontoAtencao) é uma
-- linha por cliente e chave de identidade: reavaliar não duplica; o que deixou de ocorrer vira RESOLVIDO; o DESCARTADO
-- não volta enquanto a evidência for a mesma (hash_evidencia).
CREATE TABLE ponto_atencao (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id        BIGINT        NOT NULL REFERENCES cliente (id) ON DELETE CASCADE,
    regra             VARCHAR(10)   NOT NULL,
    versao_regra      VARCHAR(30)   NOT NULL,
    chave             VARCHAR(300)  NOT NULL,
    severidade        VARCHAR(10)   NOT NULL, -- CRITICA | ALTA | MEDIA | INFO
    categoria         VARCHAR(15)   NOT NULL, -- CONFORMIDADE | RISCO | OPORTUNIDADE | MONITORAMENTO
    titulo            VARCHAR(300)  NOT NULL,
    descricao         VARCHAR(2000) NOT NULL,
    fundamento        VARCHAR(1000) NOT NULL,
    recomendacao      VARCHAR(1000) NOT NULL,
    valor             NUMERIC(15, 2),
    evidencias        JSONB         NOT NULL,
    hash_evidencia    VARCHAR(64)   NOT NULL,
    estado            VARCHAR(12)   NOT NULL, -- NOVO | EM_ANALISE | RESOLVIDO | DESCARTADO
    detectado_em      TIMESTAMP(6)  NOT NULL,
    confirmado_em     TIMESTAMP(6)  NOT NULL, -- última avaliação em que a condição ocorria
    CONSTRAINT uk_ponto_atencao UNIQUE (cliente_id, chave)
);
CREATE INDEX ix_ponto_atencao_cliente ON ponto_atencao (cliente_id, estado);

CREATE TABLE ponto_atencao_historico (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ponto_id    BIGINT        NOT NULL REFERENCES ponto_atencao (id) ON DELETE CASCADE,
    de          VARCHAR(12),
    para        VARCHAR(12)   NOT NULL,
    comentario  VARCHAR(1000),
    usuario_id  BIGINT        REFERENCES usuario (id), -- nulo: o próprio sistema (reavaliação)
    em          TIMESTAMP(6)  NOT NULL
);
CREATE INDEX ix_ponto_atencao_historico ON ponto_atencao_historico (ponto_id);

-- Última avaliação do cliente: quando e as regras que não puderam ser avaliadas (o que falta importar).
CREATE TABLE avaliacao_pontos (
    cliente_id     BIGINT       PRIMARY KEY REFERENCES cliente (id) ON DELETE CASCADE,
    avaliado_em    TIMESTAMP(6) NOT NULL,
    nao_avaliadas  JSONB        NOT NULL
);

-- Parâmetros das regras por escritório (sobrepõem os padrões de regras.json); auditado.
CREATE TABLE parametro_ponto_atencao (
    escritorio_id  BIGINT       NOT NULL REFERENCES escritorio (id) ON DELETE CASCADE,
    regra          VARCHAR(10)  NOT NULL,
    parametros     JSONB        NOT NULL,
    severidade     VARCHAR(10),
    atualizado_em  TIMESTAMP(6) NOT NULL,
    atualizado_por BIGINT       NOT NULL REFERENCES usuario (id),
    PRIMARY KEY (escritorio_id, regra)
);
