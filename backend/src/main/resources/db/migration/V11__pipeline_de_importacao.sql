-- Pipeline de importação (Fase 1): o documento pertence ao escritório e o cliente pode vir do próprio arquivo;
-- tipo, período e empresa passam a ser lidos do conteúdo. Etapas e progresso ficam no job.

ALTER TABLE documento_fiscal ADD COLUMN escritorio_id BIGINT;
UPDATE documento_fiscal d SET escritorio_id = c.escritorio_id FROM cliente c WHERE c.id = d.cliente_id;
ALTER TABLE documento_fiscal
    ALTER COLUMN escritorio_id SET NOT NULL,
    ADD CONSTRAINT fk_documento_escritorio FOREIGN KEY (escritorio_id) REFERENCES escritorio (id),
    ALTER COLUMN cliente_id DROP NOT NULL,
    ALTER COLUMN periodo_inicio DROP NOT NULL,
    ALTER COLUMN periodo_fim DROP NOT NULL,
    ALTER COLUMN esfera DROP NOT NULL,
    ALTER COLUMN juridicao DROP NOT NULL,
    -- tipo informado no upload (só sugestão: vale o detectado no conteúdo)
    ADD COLUMN tipo_informado VARCHAR(40),
    -- empresa lida do arquivo, sugerida quando o CNPJ não bate com nenhum cliente do escritório
    ADD COLUMN cnpj_arquivo VARCHAR(14),
    ADD COLUMN nome_empresa_arquivo VARCHAR(255);

-- Duplicado agora é por escritório (o upload pode chegar sem cliente). Sem UNIQUE: bases antigas podem ter o
-- mesmo arquivo em dois clientes do mesmo escritório; a regra fica no serviço.
ALTER TABLE documento_fiscal DROP CONSTRAINT uk_documento_cliente_sha256;
CREATE INDEX ix_documento_escritorio_sha256 ON documento_fiscal (escritorio_id, sha256);
CREATE INDEX ix_documento_escritorio_data ON documento_fiscal (escritorio_id, data_importacao DESC);

ALTER TABLE job_processamento
    ADD COLUMN etapa     VARCHAR(20) NOT NULL DEFAULT 'RECEBIDO',
    ADD COLUMN progresso INTEGER     NOT NULL DEFAULT 0;
UPDATE job_processamento SET etapa = 'CONCLUIDO', progresso = 100 WHERE status IN ('CONCLUIDO', 'ERRO');

CREATE TABLE inconsistencia_importacao (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id BIGINT        NOT NULL REFERENCES documento_fiscal (id) ON DELETE CASCADE,
    severidade   VARCHAR(10)   NOT NULL,
    registro     VARCHAR(40),
    linha        BIGINT,
    regra        VARCHAR(80)   NOT NULL,
    mensagem     VARCHAR(2000) NOT NULL
);
CREATE INDEX ix_inconsistencia_documento ON inconsistencia_importacao (documento_id);
