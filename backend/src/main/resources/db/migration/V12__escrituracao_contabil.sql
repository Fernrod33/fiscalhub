-- Fase 1: dados contábeis lidos dos arquivos (ECD e balancete em planilha). Tudo pendurado no documento de origem:
-- excluir ou reprocessar o documento apaga o que ele gerou (ON DELETE CASCADE).
-- Valores com sinal na convenção única: devedor positivo, credor negativo.

CREATE TABLE escrituracao_contabil (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento_id      BIGINT       NOT NULL REFERENCES documento_fiscal (id) ON DELETE CASCADE,
    cliente_id        BIGINT       NOT NULL REFERENCES cliente (id),
    origem            VARCHAR(20)  NOT NULL, -- ECD | PLANILHA
    data_inicio       DATE         NOT NULL,
    data_fim          DATE         NOT NULL,
    versao_leiaute    VARCHAR(10),           -- I010.COD_VER_LC
    plano_referencial VARCHAR(4),            -- 0000.COD_PLAN_REF (I051 no leiaute 7)
    finalidade        VARCHAR(20)  NOT NULL, -- ORIGINAL | SUBSTITUTA
    situacao          VARCHAR(20)  NOT NULL, -- VIGENTE | SUBSTITUIDA
    data_criacao      TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_escrituracao_documento ON escrituracao_contabil (documento_id);
CREATE INDEX ix_escrituracao_cliente ON escrituracao_contabil (cliente_id, data_fim);

-- Plano de contas da empresa (I050/I051 ou colunas da planilha), por escrituração
CREATE TABLE conta_contabil (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id    BIGINT       NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    codigo             VARCHAR(60)  NOT NULL,
    codigo_superior    VARCHAR(60),
    nivel              INTEGER,
    natureza           VARCHAR(2),           -- I050.COD_NAT: 01 ativo, 02 passivo, 03 PL, 04 resultado, 05 compensação, 09 outras
    sintetica          BOOLEAN      NOT NULL,
    nome               VARCHAR(500) NOT NULL,
    codigo_referencial VARCHAR(60),          -- I051.COD_CTA_REF ou de-para da planilha
    registro           VARCHAR(40)  NOT NULL,
    linha              BIGINT       NOT NULL,
    CONSTRAINT uk_conta_escrituracao_codigo UNIQUE (escrituracao_id, codigo)
);

-- Saldos por conta e período: I155 (saldos periódicos), I355 (resultado antes do encerramento) ou planilha
CREATE TABLE saldo_conta (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id BIGINT         NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    conta_id        BIGINT         NOT NULL REFERENCES conta_contabil (id) ON DELETE CASCADE,
    origem          VARCHAR(10)    NOT NULL, -- I155 | I355 | PLANILHA
    centro_custo    VARCHAR(60),
    data_inicio     DATE,
    data_fim        DATE           NOT NULL,
    saldo_inicial   NUMERIC(19, 2),
    debitos         NUMERIC(19, 2),
    creditos        NUMERIC(19, 2),
    saldo_final     NUMERIC(19, 2) NOT NULL,
    registro        VARCHAR(40)    NOT NULL, -- registro SPED ou aba da planilha
    linha           BIGINT         NOT NULL
);
CREATE INDEX ix_saldo_escrituracao ON saldo_conta (escrituracao_id, origem, data_fim);
CREATE INDEX ix_saldo_conta ON saldo_conta (conta_id);

-- Demonstrações: PUBLICADA (J100/J150 da empresa) ou REFERENCIAL (montada pelo sistema a partir dos saldos mapeados)
CREATE TABLE demonstracao (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrituracao_id   BIGINT      NOT NULL REFERENCES escrituracao_contabil (id) ON DELETE CASCADE,
    tipo              VARCHAR(3)  NOT NULL, -- BP | DRE
    origem            VARCHAR(12) NOT NULL, -- PUBLICADA | REFERENCIAL
    data_inicio       DATE,
    data_fim          DATE        NOT NULL,
    exercicio         INTEGER     NOT NULL,
    tabela_referencial VARCHAR(40)          -- tabela oficial usada na montagem referencial
);
CREATE INDEX ix_demonstracao_escrituracao ON demonstracao (escrituracao_id);

CREATE TABLE linha_demonstracao (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demonstracao_id BIGINT         NOT NULL REFERENCES demonstracao (id) ON DELETE CASCADE,
    codigo          VARCHAR(60)    NOT NULL,
    descricao       VARCHAR(500)   NOT NULL,
    nivel           INTEGER,
    codigo_superior VARCHAR(60),
    ordem           INTEGER        NOT NULL,
    totalizadora    BOOLEAN        NOT NULL,
    grupo           VARCHAR(1),              -- BP: A ativo / P passivo e PL; DRE: R receita / D despesa
    valor_inicial   NUMERIC(19, 2),
    valor_final     NUMERIC(19, 2),
    registro        VARCHAR(40),             -- origem da publicada (J100/J150); referencial: ver linha_demonstracao_conta
    linha           BIGINT
);
CREATE INDEX ix_linha_demonstracao ON linha_demonstracao (demonstracao_id, ordem);

-- Contas da empresa que compõem cada linha analítica do referencial (navegação até a origem)
CREATE TABLE linha_demonstracao_conta (
    linha_id BIGINT NOT NULL REFERENCES linha_demonstracao (id) ON DELETE CASCADE,
    conta_id BIGINT NOT NULL REFERENCES conta_contabil (id) ON DELETE CASCADE,
    PRIMARY KEY (linha_id, conta_id)
);
