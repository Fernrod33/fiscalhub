-- Relatórios emitidos: imutáveis e reproduzíveis. Guarda os parâmetros, o snapshot do modelo (texto JSON exato, para o
-- SHA-256 conferir), as versões do template e das tabelas/normas, o PDF e o Excel no storage (com SHA-256) e quem
-- emitiu. Número sequencial por escritório. Reemitir cria outro registro; nada aqui é alterado depois.
CREATE TABLE relatorio_emitido (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escritorio_id   BIGINT       NOT NULL REFERENCES escritorio (id),
    cliente_id      BIGINT       NOT NULL REFERENCES cliente (id),
    numero          BIGINT       NOT NULL,
    tipo            VARCHAR(30)  NOT NULL,
    parametros      JSONB        NOT NULL,
    snapshot        TEXT         NOT NULL,
    sha256_snapshot VARCHAR(64)  NOT NULL,
    versao_template VARCHAR(40)  NOT NULL,
    versao_normas   VARCHAR(200) NOT NULL,
    chave_pdf       VARCHAR(300) NOT NULL,
    sha256_pdf      VARCHAR(64)  NOT NULL,
    tamanho_pdf     BIGINT       NOT NULL,
    chave_xlsx      VARCHAR(300) NOT NULL,
    sha256_xlsx     VARCHAR(64)  NOT NULL,
    tamanho_xlsx    BIGINT       NOT NULL,
    emitido_por_id  BIGINT       NOT NULL REFERENCES usuario (id),
    emitido_em      TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_relatorio_numero UNIQUE (escritorio_id, numero)
);

CREATE INDEX ix_relatorio_emitido_cliente ON relatorio_emitido (cliente_id, emitido_em DESC);

-- Imutável: nenhuma alteração depois da emissão.
CREATE FUNCTION relatorio_emitido_imutavel() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'relatorio_emitido é imutável (relatório %): emita outro', OLD.numero;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER tg_relatorio_emitido_imutavel BEFORE UPDATE ON relatorio_emitido
    FOR EACH ROW EXECUTE FUNCTION relatorio_emitido_imutavel();
