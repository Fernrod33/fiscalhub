-- Sessão por dispositivo: o JWT leva o id (sid); encerrar uma sessão revoga só ela. A versão do token no usuário
-- continua derrubando todas (troca de senha, desativação, mudança de papel).
CREATE TABLE sessao (
    id           UUID          PRIMARY KEY,
    usuario_id   BIGINT        NOT NULL REFERENCES usuario (id),
    criada_em    TIMESTAMP(6)  NOT NULL,
    ultimo_uso   TIMESTAMP(6)  NOT NULL,
    expira_em    TIMESTAMP(6)  NOT NULL,
    ip           VARCHAR(45),
    dispositivo  VARCHAR(300),
    revogada_em  TIMESTAMP(6)
);
CREATE INDEX ix_sessao_usuario ON sessao (usuario_id, revogada_em);

-- Segundo fator (TOTP): segredo cifrado com CHAVE_DADOS (AES-GCM), último passo aceito (o mesmo código não vale duas
-- vezes) e códigos de recuperação de uso único guardados como SHA-256.
ALTER TABLE usuario
    ADD COLUMN totp_segredo      VARCHAR(200),
    ADD COLUMN totp_ativo        BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN totp_ultimo_passo BIGINT;

CREATE TABLE codigo_recuperacao (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id  BIGINT       NOT NULL REFERENCES usuario (id),
    hash        CHAR(64)     NOT NULL,
    usado_em    TIMESTAMP(6)
);
CREATE INDEX ix_codigo_recuperacao_usuario ON codigo_recuperacao (usuario_id);

-- O ADMIN pode exigir o segundo fator de todo o escritório.
ALTER TABLE escritorio ADD COLUMN exigir_segundo_fator BOOLEAN NOT NULL DEFAULT FALSE;
