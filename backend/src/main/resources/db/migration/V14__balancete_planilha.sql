-- Balancete em planilha: mapeamento de colunas salvo por cliente (reconhecido pela assinatura do cabeçalho) e de-para
-- das contas do cliente para o plano referencial. O usuário só aponta colunas e escolhe contas: nenhum valor digitado.

CREATE TABLE mapeamento_planilha (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id        BIGINT       NOT NULL REFERENCES cliente (id) ON DELETE CASCADE,
    assinatura        VARCHAR(64)  NOT NULL, -- SHA-256 do cabeçalho normalizado
    aba               VARCHAR(200),
    linha_cabecalho   INTEGER      NOT NULL, -- 1 = primeira linha da planilha
    col_codigo        INTEGER      NOT NULL, -- colunas a partir de 0 (A = 0)
    col_descricao     INTEGER      NOT NULL,
    col_saldo_inicial INTEGER,
    col_debitos       INTEGER,
    col_creditos      INTEGER,
    col_saldo_final   INTEGER      NOT NULL,
    col_dc_inicial    INTEGER,               -- indicador D/C em coluna própria (sem ela: no valor ou pelo sinal)
    col_dc_final      INTEGER,
    plano_referencial VARCHAR(4)   NOT NULL,
    atualizado_em     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_mapeamento_cliente_assinatura UNIQUE (cliente_id, assinatura)
);

CREATE TABLE depara_referencial (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id         BIGINT       NOT NULL REFERENCES cliente (id) ON DELETE CASCADE,
    codigo_conta       VARCHAR(60)  NOT NULL,
    codigo_referencial VARCHAR(60)  NOT NULL,
    atualizado_em      TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_depara_cliente_conta UNIQUE (cliente_id, codigo_conta)
);
