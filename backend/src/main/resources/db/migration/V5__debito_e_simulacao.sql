-- Fim do cadastro manual: Debito (sempre ligado ao documento importado) substitui Declaracao,
-- e a simulacao passa a consolidar varios debitos de um cliente.
-- ATENCAO: apaga as simulacoes antigas (dependiam de declaracoes digitadas) e a tabela declaracao.

CREATE TABLE debito (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id          BIGINT        NOT NULL REFERENCES cliente (id),
    documento_origem_id BIGINT        NOT NULL REFERENCES documento_fiscal (id),
    referencia_origem   VARCHAR(200),
    orgao_credor        VARCHAR(20)   NOT NULL,
    tributo             VARCHAR(20)   NOT NULL,
    competencia         DATE,
    data_vencimento     DATE          NOT NULL,
    valor_principal     NUMERIC(15,2) NOT NULL,
    valor_multa         NUMERIC(15,2),
    valor_juros         NUMERIC(15,2),
    situacao            VARCHAR(30)   NOT NULL,
    numero_inscricao    VARCHAR(60),
    data_criacao        TIMESTAMP(6)  NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_debito_cliente ON debito (cliente_id);
CREATE INDEX ix_debito_documento_origem ON debito (documento_origem_id);

DELETE FROM parcela_simulacao;
DELETE FROM simulacao_parcelamento;

ALTER TABLE simulacao_parcelamento
    DROP COLUMN declaracao_id,
    DROP COLUMN taxa_juros,
    DROP COLUMN valor_total,
    ADD COLUMN cliente_id BIGINT NOT NULL REFERENCES cliente (id);
CREATE INDEX ix_simulacao_cliente ON simulacao_parcelamento (cliente_id);

CREATE TABLE simulacao_debito (
    simulacao_id BIGINT NOT NULL REFERENCES simulacao_parcelamento (id) ON DELETE CASCADE,
    debito_id    BIGINT NOT NULL REFERENCES debito (id),
    PRIMARY KEY (simulacao_id, debito_id)
);

DROP TABLE declaracao;
