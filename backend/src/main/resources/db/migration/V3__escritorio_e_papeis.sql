-- Escritorio e papeis. Cada usuario existente ganha um escritorio proprio (nome = nome do usuario) e vira ADMIN.

CREATE TABLE escritorio (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome             VARCHAR(150) NOT NULL,
    documento        VARCHAR(14),
    ativo            BOOLEAN      NOT NULL DEFAULT TRUE,
    data_criacao     TIMESTAMP(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP(6),
    usuario_origem_id BIGINT -- auxiliar desta migracao, removida abaixo
);

INSERT INTO escritorio (nome, usuario_origem_id)
SELECT nome, id FROM usuario;

ALTER TABLE usuario
    ADD COLUMN escritorio_id BIGINT,
    ADD COLUMN papel VARCHAR(20),
    ADD COLUMN trocar_senha_no_proximo_login BOOLEAN NOT NULL DEFAULT FALSE;

UPDATE usuario u
SET escritorio_id = e.id, papel = 'ADMIN'
FROM escritorio e
WHERE e.usuario_origem_id = u.id;

ALTER TABLE escritorio DROP COLUMN usuario_origem_id;

ALTER TABLE usuario
    ALTER COLUMN escritorio_id SET NOT NULL,
    ALTER COLUMN papel SET NOT NULL,
    ADD CONSTRAINT fk_usuario_escritorio FOREIGN KEY (escritorio_id) REFERENCES escritorio (id);

CREATE INDEX ix_usuario_escritorio ON usuario (escritorio_id);
